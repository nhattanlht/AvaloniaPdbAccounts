-- Drop existing users U1-U8 if they exist
DECLARE
  v_sql VARCHAR2(200);
BEGIN
  FOR i IN 1..8 LOOP
    BEGIN
      v_sql := 'DROP USER U' || i || ' CASCADE';
      EXECUTE IMMEDIATE v_sql;
      DBMS_OUTPUT.PUT_LINE('Dropped user U' || i);
    EXCEPTION
      WHEN OTHERS THEN 
        DBMS_OUTPUT.PUT_LINE('User U' || i || ' does not exist or error: ' || SQLERRM);
    END;
  END LOOP;
END;
/

